#!/usr/bin/env python3
"""Write KEYBINDINGS.md from the keys the configuration really registers.

The list is not typed by hand: HyDE's key_binds.lua and then island.lua (which registers
Configs/.config/hypr/keybinds.lua and unbinds what that list reassigns) are loaded under a recording
stand-in for Hyprland's `hl` table, in the order Hyprland loads them. What is left, after the
unbinds and the later-wins rule, is the list a fresh install ends up with. A machine's own
host.lua and desktop.lua are not part of it.

    python3 tools/gen_keybindings.py            rewrite KEYBINDINGS.md
    python3 tools/gen_keybindings.py --check    exit 1 if KEYBINDINGS.md is out of date

Needs the system `lua`.
"""
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
HYPR = ROOT / "Configs/.config/hypr"
HYDE_BINDS = ROOT / "Configs/.local/share/hypr/lua/key_binds.lua"
OUT = ROOT / "KEYBINDINGS.md"

RECORDER = r"""
local function proxy()
  return setmetatable({}, {__index = function() return proxy() end, __call = function() return proxy() end,
    __concat = function() return "" end, __tostring = function() return "" end})
end
local log = {}
local function esc(s) return '"' .. tostring(s):gsub('\\', '\\\\'):gsub('"', '\\"'):gsub('\n', ' ') .. '"' end
hl = proxy()
hl.bind = function(k, _, o) log[#log + 1] = '{"op":"bind","keys":' .. esc(k) .. ',"desc":' .. esc((o or {}).description or "") .. '}' end
hl.unbind = function(k) log[#log + 1] = '{"op":"unbind","keys":' .. esc(k) .. '}' end
hyde = proxy()
hyde.config = {modifiers = {main = "SUPER"}, start = {}, app = setmetatable({}, {__index = function() return "" end})}
hyde.binds = {}
for i = 1, #arg do
  local ok, err = pcall(dofile, arg[i])
  if not ok then io.stderr:write(arg[i] .. ": " .. tostring(err) .. "\n"); os.exit(2) end
end
print("[" .. table.concat(log, ",") .. "]")
"""

MODS = {"SUPER": "Super", "SHIFT": "Shift", "CTRL": "Ctrl", "CONTROL": "Ctrl", "ALT": "Alt"}
ORDER = ["Super", "Ctrl", "Alt", "Shift"]


def combo(spec):
    """'SUPER + SHIFT + T' (any order, any case, CONTROL or CTRL) -> ('Super','Shift','T') normalised."""
    parts = [p for p in " ".join(spec.split("+")).split()]
    mods = sorted({MODS[p.upper()] for p in parts if p.upper() in MODS}, key=ORDER.index)
    keys = [p for p in parts if p.upper() not in MODS]
    return tuple(mods), (keys[0] if keys else "")


def record():
    if not shutil.which("lua"):
        sys.exit("gen_keybindings: needs the system `lua`")
    with tempfile.TemporaryDirectory() as home:
        dst = pathlib.Path(home) / ".config/hypr"
        dst.mkdir(parents=True)
        shutil.copy(HYPR / "keybinds.lua", dst / "keybinds.lua")
        env = {"HOME": home, "XDG_STATE_HOME": home + "/state", "PATH": "/usr/bin:/bin"}
        out = subprocess.run(["lua", "-", str(HYDE_BINDS), str(HYPR / "island.lua")],
                             input=RECORDER, capture_output=True, text=True, env=env)
    if out.returncode:
        sys.exit("gen_keybindings: " + out.stderr.strip())
    return json.loads(out.stdout)


def final(log):
    live = {}
    for e in log:
        c = combo(e["keys"])
        if e["op"] == "unbind":
            live.pop(c, None)
        else:
            live[c] = e["desc"]
    return live


def render(live):
    groups = {}
    for (mods, key), desc in live.items():
        head, _, text = desc.partition("] ")
        cats = head.lstrip("[").split("|") if text else ["Other"]
        groups.setdefault(cats[0], []).append((cats[1:], mods, key, text or desc or "(no description)"))
    lines = ["# Keybindings", "",
             "Generated by `tools/gen_keybindings.py` from the keys the configuration registers: HyDE's",
             "`Configs/.local/share/hypr/lua/key_binds.lua`, then `Configs/.config/hypr/keybinds.lua` (the",
             "one list this repository adds, see the layers below). Do not edit this file by hand;",
             "`python3 tools/gen_keybindings.py --check` fails when it is out of date.", "",
             "> [!TIP]", "> <kbd>Super</kbd> + <kbd>\\</kbd> shows the keybindings that are active on your machine,",
             "> machine-specific ones included.", "",
             "## How the keys are laid out", "",
             "| Modifier | Meaning |", "|---|---|",
             "| `Super` + key | use or open something |",
             "| `Super` + `Shift` + key | pick or change something |",
             "| `Super` + `Ctrl` + arrows | step through something (wallpaper left/right, palette up/down) |",
             "| `Super` + `Alt` + key | system and rare things |", "",
             "Keys that exist in only one of the two shells (the island or the HyDE bar) do nothing in the other.", ""]
    for cat in sorted(groups):
        lines += ["## " + cat, "", "| Keys | Does |", "|---|---|"]
        for sub, mods, key, text in sorted(groups[cat], key=lambda r: (r[0], r[3].lower(), r[1], r[2])):
            keys = " + ".join("<kbd>%s</kbd>" % k for k in list(mods) + [key])
            label = ("%s: %s" % (" / ".join(sub), text)) if sub else text
            lines.append("| %s | %s |" % (keys, label.replace("|", "\\|")))
        lines.append("")
    return "\n".join(lines)


def main():
    text = render(final(record()))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("KEYBINDINGS.md is out of date: run python3 tools/gen_keybindings.py")
        return
    OUT.write_text(text, encoding="utf-8")
    print("%s: %d keys" % (OUT.name, len(final(record()))))


if __name__ == "__main__":
    main()
